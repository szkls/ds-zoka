// Generates src/icons/paths.ts from tokens/figma/icons/*.json (SVG path data exported from the Figma icon set, 32×32 viewBox).
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => JSON.parse(readFileSync(resolve(root, p), 'utf8'));
const stroke = { ...read('tokens/figma/icons/stroke-1.json'), ...read('tokens/figma/icons/stroke-2.json') };
const fill = read('tokens/figma/icons/fill.json');
const out = [
  '// Generated by scripts/build-icons.mjs — do not edit. Source: tokens/figma/icons/*.json',
  '// Each icon is drawn on a 32×32 viewBox. "stroke" paths are stroked (Figma Format=Stroke, Weight=Regular),',
  '// "fill" paths are filled (Figma Format=Outline, Weight=Fill).',
  `export const strokeIcons = ${JSON.stringify(stroke)} as const;`,
  `export const fillIcons = ${JSON.stringify(fill)} as const;`,
  'export type IconName = keyof typeof strokeIcons;',
  'export type FillIconName = keyof typeof fillIcons;',
  `export const iconNames = ${JSON.stringify(Object.keys(stroke))} as const;`,
  '',
];
writeFileSync(resolve(root, 'src/icons/paths.ts'), out.join('\n'));
console.log('icons:', Object.keys(stroke).length, 'stroke,', Object.keys(fill).length, 'fill');
